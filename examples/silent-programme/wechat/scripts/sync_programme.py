#!/usr/bin/env python3
"""Build and verify the standalone mini-program from the shared programme."""
import argparse
import filecmp
import json
import math
import os
from pathlib import Path
import shutil
import tempfile

PROJECT = Path(__file__).resolve().parents[1]
SOURCE = PROJECT.parent


def safe_mode(film, image, frame_ratio):
    """Mirror the renderer's protection-first fit resolution for Mini Program."""
    spec = film.get("composition") or {}
    region = spec.get("protectedRegion") or {"x": 0, "y": 0, "width": 1, "height": 1}
    if not isinstance(region, dict) or set(region) != {"x", "y", "width", "height"}:
        raise ValueError(f"Invalid protectedRegion for {film['id']}")
    if any(isinstance(region[key], bool) for key in region):
        raise ValueError(f"Invalid protectedRegion for {film['id']}")
    try:
        region = {key: float(region[key]) for key in region}
    except (TypeError, ValueError):
        raise ValueError(f"Invalid protectedRegion for {film['id']}") from None
    if (not all(math.isfinite(value) for value in region.values()) or region["x"] < 0 or region["y"] < 0
            or region["width"] <= 0 or region["height"] <= 0 or region["x"] + region["width"] > 1
            or region["y"] + region["height"] > 1):
        raise ValueError(f"Invalid protectedRegion for {film['id']}")
    if spec.get("fit", "contain") != "cover":
        return "aspectFit"
    from PIL import Image
    with Image.open(image) as opened:
        source_ratio = opened.width / opened.height
    if source_ratio > frame_ratio:
        visible = frame_ratio / source_ratio
        center = min(max(region["x"] + region["width"] / 2, visible / 2), 1 - visible / 2)
        safe = region["width"] <= visible and region["x"] >= center - visible / 2 and region["x"] + region["width"] <= center + visible / 2
    else:
        visible = source_ratio / frame_ratio
        center = min(max(region["y"] + region["height"] / 2, visible / 2), 1 - visible / 2)
        safe = region["height"] <= visible and region["y"] >= center - visible / 2 and region["y"] + region["height"] <= center + visible / 2
    return "aspectFill" if safe else "aspectFit"


def build(check):
    programme = json.loads((SOURCE / "programme.json").read_text(encoding="utf-8"))
    films = programme["films"]
    ids = [film["id"] for film in films]
    if not ids or not all(isinstance(i, str) and i for i in ids) or len(set(ids)) != len(ids):
        raise ValueError("Each film must have a unique, non-empty id")
    images = {}
    for film in films:
        path = Path(film["image"])
        if path.parent != Path("assets") or not (SOURCE / path).is_file():
            raise ValueError(f"Missing image under assets/: {path}")
        images[path] = SOURCE / path

    # Keep source JSON immutable while making each Mini Program frame consume
    # the same declared composition.  aspectFit is the safe downgrade.
    programme = {**programme, "films": [
        {**film, "delivery": {
            "mobile": {"mode": safe_mode(film, SOURCE / film["image"], 200 / 144)},
            "detail": {"mode": safe_mode(film, SOURCE / film["image"], 690 / 480)},
        }} for film in films
    ]}

    out = PROJECT / "data/programme.js"
    content = "// Generated by scripts/sync_programme.py. Do not hand-edit.\nmodule.exports = "
    content += json.dumps(programme, ensure_ascii=False, indent=2) + ";\n"
    if check:
        if out.read_text(encoding="utf-8") != content:
            raise ValueError("Programme data changed. Run sync_programme.py")
        for path, source in images.items():
            if not (PROJECT / path).is_file() or not filecmp.cmp(source, PROJECT / path, shallow=False):
                raise ValueError(f"Asset differs from the source: {path}")
        print("PASS all programme data and image bytes match")
        return

    with tempfile.TemporaryDirectory(dir=PROJECT) as directory:
        temp = Path(directory)
        for path, source in images.items():
            (temp / path.parent).mkdir(exist_ok=True)
            try:
                os.link(source, temp / path)
            except OSError:
                shutil.copyfile(source, temp / path)
        pending_data = temp / "programme.js"
        pending_data.write_text(content, encoding="utf-8")
        for path in images:
            (PROJECT / path.parent).mkdir(exist_ok=True)
            os.replace(temp / path, PROJECT / path)
        out.parent.mkdir(exist_ok=True)
        os.replace(pending_data, out)
    print(f"Synchronised {len(films)} films")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    build(parser.parse_args().check)
